"""Alembic environment (async engine). Database URL comes from XBOT_DATABASE_URL / .env."""

from __future__ import annotations

import asyncio
from logging.config import fileConfig

from sqlalchemy.ext.asyncio import async_engine_from_config
from sqlalchemy.pool import NullPool

from alembic import context
from xbot.config import get_settings
from xbot.db import models  # noqa: F401  (registers tables on Base.metadata)
from xbot.db.base import Base

config = context.config
if config.config_file_name is not None:
    fileConfig(config.config_file_name)

config.set_main_option("sqlalchemy.url", get_settings().database_url)
target_metadata = Base.metadata

LANGGRAPH_TABLE_PREFIX = "checkpoint"


def include_object(obj, name, type_, reflected, compare_to):  # type: ignore[no-untyped-def]
    """LangGraph owns its checkpoint tables (created by AsyncPostgresSaver.setup()); never let
    autogenerate try to drop or alter them."""
    return not (type_ == "table" and name is not None and name.startswith(LANGGRAPH_TABLE_PREFIX))


def run_migrations_offline() -> None:
    context.configure(
        url=config.get_main_option("sqlalchemy.url"),
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
        include_object=include_object,
    )
    with context.begin_transaction():
        context.run_migrations()


def _do_run_migrations(connection) -> None:  # type: ignore[no-untyped-def]
    context.configure(
        connection=connection, target_metadata=target_metadata, include_object=include_object
    )
    with context.begin_transaction():
        context.run_migrations()


async def run_migrations_online() -> None:
    connectable = async_engine_from_config(
        config.get_section(config.config_ini_section, {}),
        prefix="sqlalchemy.",
        poolclass=NullPool,
    )
    async with connectable.connect() as connection:
        await connection.run_sync(_do_run_migrations)
    await connectable.dispose()


if context.is_offline_mode():
    run_migrations_offline()
else:
    asyncio.run(run_migrations_online())
